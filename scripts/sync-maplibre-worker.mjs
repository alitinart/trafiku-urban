// MapLibre v6 locates its worker via import.meta.url, which Metro doesn't provide.
// Web: serve the worker from /public. Native (DOM component in a WebView): embed the
// source so it can be spawned from a Blob URL. Runs on postinstall.
import fs from 'node:fs';
import path from 'node:path';
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const src = path.join(ROOT, 'node_modules/maplibre-gl/dist/maplibre-gl-worker.mjs');
const code = fs.readFileSync(src, 'utf8');
fs.writeFileSync(path.join(ROOT, 'public/maplibre-gl-worker.mjs'), code);
fs.writeFileSync(
  path.join(ROOT, 'src/map/workerSource.generated.ts'),
  `// generated by scripts/sync-maplibre-worker.mjs — do not edit\nexport default ${JSON.stringify(code)};\n`,
);
console.log('maplibre worker synced');
